    ON sar_archivo.asignacion_referencia (ubicacion_id);

CREATE INDEX idx_asignacion_referencia_referencia
    ON sar_archivo.asignacion_referencia (referencia_id);

CREATE INDEX idx_asignacion_referencia_estado
    ON sar_archivo.asignacion_referencia (estado_id);

CREATE INDEX idx_asignacion_referencia_usuario
    ON sar_archivo.asignacion_referencia (usuario_asignacion);


-- ============================================================================
-- CONSULTA PRINCIPAL DEL HISTORIAL DE UNA UBICACIÓN
-- ============================================================================
-- Este índice permite obtener rápidamente todos los intentos de una ubicación
-- ordenados por fecha.
-- ============================================================================

CREATE INDEX idx_asignacion_ubicacion_fecha
    ON sar_archivo.asignacion_referencia (
        ubicacion_id,
        fecha_asignacion DESC
    );


