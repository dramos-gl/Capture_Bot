-- Tabla: factura
CREATE TABLE sar_archivo.factura (
    factura_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia_id BIGINT NOT NULL,
    uuid VARCHAR(36) NOT NULL UNIQUE,
    nombre_archivo VARCHAR(100),
    rfc_emisor VARCHAR(13) NOT NULL,
    fecha_factura TIMESTAMPTZ NOT NULL,
    pdf_path VARCHAR(1000),
    pdf2_path VARCHAR(1000),
    estado VARCHAR(30) NOT NULL,
    delegacion VARCHAR(100),
    FOREIGN KEY (referencia_id) REFERENCES sar_produccion.referencia(referencia_id) ON DELETE RESTRICT
);

-- Tabla: lote_asignacion
CREATE TABLE sar_archivo.lote_asignacion (
    lote_asignacion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_destino VARCHAR(20) NOT NULL, -- 'NOTARIA' o 'COLABORADOR'
    notaria_id BIGINT,
    colaborador_id BIGINT,
    solicitante_externo VARCHAR(200),
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    observaciones TEXT,
    usuario_creacion BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (notaria_id) REFERENCES sar_catalogo.notaria(notaria_id) ON DELETE RESTRICT,
    FOREIGN KEY (colaborador_id) REFERENCES sar_catalogo.colaborador(colaborador_id) ON DELETE RESTRICT,
    FOREIGN KEY (usuario_creacion) REFERENCES sar_seguridad.usuario(usuario_id) ON DELETE RESTRICT,
    CONSTRAINT chk_lote_asignacion_tipo_destino CHECK (tipo_destino IN ('NOTARIA', 'COLABORADOR')),
    CONSTRAINT chk_lote_asignacion_destino CHECK (
        (tipo_destino = 'NOTARIA' AND notaria_id IS NOT NULL AND colaborador_id IS NULL)
        OR
        (tipo_destino = 'COLABORADOR' AND colaborador_id IS NOT NULL AND notaria_id IS NULL)
    )
);

-- Tabla: ubicacion
CREATE TABLE sar_archivo.ubicacion (
    ubicacion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    desarrollo_id BIGINT NOT NULL,
    sm VARCHAR(50),
    mz VARCHAR(50),
    lote VARCHAR(50),
    edif VARCHAR(50),
    viv VARCHAR(50),
    lote_id_erp VARCHAR(100),
    descripcion TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (desarrollo_id) REFERENCES sar_catalogo.desarrollo(desarrollo_id) ON DELETE RESTRICT
);

-- Tabla: lote_detalle
CREATE TABLE sar_archivo.lote_detalle (
    lote_detalle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_asignacion_id BIGINT NOT NULL,
    rfc_id BIGINT NOT NULL,
    concepto_id BIGINT NOT NULL,
    desarrollo_id BIGINT,
    cantidad_solicitada INTEGER NOT NULL,
    cantidad_confirmada INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (lote_asignacion_id) REFERENCES sar_archivo.lote_asignacion(lote_asignacion_id) ON DELETE CASCADE,
    FOREIGN KEY (rfc_id) REFERENCES sar_catalogo.rfc(rfc_id) ON DELETE RESTRICT,
    FOREIGN KEY (concepto_id) REFERENCES sar_catalogo.concepto(concepto_id) ON DELETE RESTRICT,
    FOREIGN KEY (desarrollo_id) REFERENCES sar_catalogo.desarrollo(desarrollo_id) ON DELETE RESTRICT
);

-- Tabla: asignacion_referencia
CREATE TABLE sar_archivo.asignacion_referencia (
    asignacion_referencia_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_detalle_id BIGINT NOT NULL,
    referencia_id BIGINT NOT NULL,
    ubicacion_id BIGINT,
    intento INTEGER NOT NULL DEFAULT 1,
    estado_id BIGINT NOT NULL,
    cliente VARCHAR(250),
    credito_titular VARCHAR(250),
    pa VARCHAR(250),
    no_oficial VARCHAR(250),
    fecha_solicitud DATE,
    fecha_reporte_notaria DATE,
    fecha_ingreso_rpp DATE,
    fecha_escritura DATE,
    fecha_titulacion DATE,
    comentarios TEXT,
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    usuario_asignacion BIGINT NOT NULL,
    fecha_confirmacion TIMESTAMPTZ,
    usuario_confirmacion BIGINT,
    observaciones TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (lote_detalle_id) REFERENCES sar_archivo.lote_detalle(lote_detalle_id) ON DELETE CASCADE,
    FOREIGN KEY (referencia_id) REFERENCES sar_produccion.referencia(referencia_id) ON DELETE RESTRICT,
    FOREIGN KEY (ubicacion_id) REFERENCES sar_archivo.ubicacion(ubicacion_id) ON DELETE RESTRICT,
    FOREIGN KEY (estado_id) REFERENCES sar_catalogo.estado_sistema(estado_id) ON DELETE RESTRICT,
    FOREIGN KEY (usuario_asignacion) REFERENCES sar_seguridad.usuario(usuario_id) ON DELETE RESTRICT,
    FOREIGN KEY (usuario_confirmacion) REFERENCES sar_seguridad.usuario(usuario_id) ON DELETE RESTRICT,
    CONSTRAINT chk_asignacion_referencia_intento CHECK (intento >= 1),
    CONSTRAINT chk_asignacion_referencia_confirmacion CHECK (
        (fecha_confirmacion IS NULL AND usuario_confirmacion IS NULL)
        OR
        (fecha_confirmacion IS NOT NULL AND usuario_confirmacion IS NOT NULL)
    ),
    CONSTRAINT uq_asignacion_referencia_referencia UNIQUE (referencia_id),
    CONSTRAINT uq_ubicacion_lote_detalle_intento UNIQUE (ubicacion_id, lote_detalle_id, intento)
);

