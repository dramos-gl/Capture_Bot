-- Tabla: folio_cancun
-- Folio individual a procesar. Unidad de trabajo de Bot Recibos y Bot Facturas.
CREATE TABLE cancunbot_produccion.folio_cancun (
    folio_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL,
    folio_electronico VARCHAR(100),    -- Folio electrónico (ej: F-2026-615-31044)
    folio_pase_caja VARCHAR(100),
    tipo_folio VARCHAR(20) NOT NULL DEFAULT 'ELECTRONICO',
    intentos INTEGER NOT NULL DEFAULT 0, -- Número de intentos de descarga realizados
    ultimo_error TEXT,
    estado_id BIGINT NOT NULL,
    rfc_id INTEGER,           -- Referencia opcional al RFC en el catálogo de SAR
    desarrollo_id INTEGER,    -- Referencia opcional al desarrollo en el catálogo de SAR
