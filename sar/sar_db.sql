    updated_at TIMESTAMPTZ,
    FOREIGN KEY (lote_id) REFERENCES cancunbot_produccion.lote_folio(lote_id) ON DELETE CASCADE,
    FOREIGN KEY (estado_id) REFERENCES sar_catalogo.estado_sistema(estado_id) ON DELETE RESTRICT,
    FOREIGN KEY (rfc_id) REFERENCES sar_catalogo.rfc(rfc_id) ON DELETE SET NULL,
    FOREIGN KEY (desarrollo_id) REFERENCES sar_catalogo.desarrollo(desarrollo_id) ON DELETE SET NULL,
    CONSTRAINT chk_folio_tipo CHECK (tipo_folio IN ('ELECTRONICO', 'PASE_CAJA')),
    CONSTRAINT chk_folio_no_nulo CHECK (folio_electronico IS NOT NULL OR folio_pase_caja IS NOT NULL)
);

