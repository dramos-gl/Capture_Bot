-- Tabla: municipio
CREATE TABLE sar_catalogo.municipio (
    municipio_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_portal VARCHAR(50),
    nombre VARCHAR(200) NOT NULL,
    activo BOOLEAN DEFAULT TRUE
);

-- Tabla: delegacion
CREATE TABLE sar_catalogo.delegacion (
    delegacion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio_id BIGINT NOT NULL,
    codigo_portal VARCHAR(300),
    nombre VARCHAR(200) NOT NULL,
    activo BOOLEAN DEFAULT TRUE,
    FOREIGN KEY (municipio_id) REFERENCES sar_catalogo.municipio(municipio_id) ON DELETE RESTRICT
);

-- Tabla: concepto
CREATE TABLE sar_catalogo.concepto (
    concepto_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_portal VARCHAR(300),
    nombre VARCHAR(300) NOT NULL,
    alias VARCHAR(20),
    activo BOOLEAN DEFAULT TRUE
);

-- Tabla: rfc
CREATE TABLE sar_catalogo.rfc (
    rfc_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfc VARCHAR(13) NOT NULL UNIQUE,
    razon_social VARCHAR(500) NOT NULL,
    calle VARCHAR(500),
    no_exterior VARCHAR(50),
    no_interior VARCHAR(50),
    colonia VARCHAR(300),
    codigo_postal VARCHAR(10),
    localidad VARCHAR(300),
    municipio VARCHAR(300),
    estado VARCHAR(300),
    activo BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    CONSTRAINT chk_rfc_pattern CHECK (rfc ~* '^[A-Z&Ññ]{3,4}[0-9]{6}[A-Z0-9]{3}$')
);

-- Tabla: estado_sistema
CREATE TABLE sar_catalogo.estado_sistema (
    estado_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad VARCHAR(100) NOT NULL,
    codigo VARCHAR(50) NOT NULL,
    descripcion VARCHAR(200),
    UNIQUE(entidad, codigo)
);

-- Tabla: notaria
CREATE TABLE sar_catalogo.notaria (
    notaria_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL UNIQUE,
    alias VARCHAR(50),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Tabla: colaborador
CREATE TABLE sar_catalogo.colaborador (
    colaborador_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Tabla: desarrollo
CREATE TABLE sar_catalogo.desarrollo (
    desarrollo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_desarrollo_nombre UNIQUE (nombre)
);

-- Tabla intermedia: desarrollo_empresa
CREATE TABLE sar_catalogo.desarrollo_empresa (
    desarrollo_empresa_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    desarrollo_id BIGINT NOT NULL,
    rfc_id BIGINT NOT NULL,
    delegacion_id BIGINT NOT NULL,
    es_default BOOLEAN NOT NULL DEFAULT FALSE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (desarrollo_id) REFERENCES sar_catalogo.desarrollo(desarrollo_id) ON DELETE RESTRICT,
    FOREIGN KEY (rfc_id) REFERENCES sar_catalogo.rfc(rfc_id) ON DELETE RESTRICT,
    FOREIGN KEY (delegacion_id) REFERENCES sar_catalogo.delegacion(delegacion_id) ON DELETE RESTRICT,
    CONSTRAINT uq_desarrollo_empresa_delegacion UNIQUE (desarrollo_id, rfc_id, delegacion_id)
);

-- Tabla: evento_sistema
CREATE TABLE sar_catalogo.evento_sistema (
    evento_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(300)
);

